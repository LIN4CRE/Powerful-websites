/**
 * Shared data contracts for the directory, the automation robots and the UI.
 * These types are the single source of truth for every JSON file in /data.
 */

export type VerificationStatus = 'verified' | 'pending' | 'rejected';
export type Availability = 'online' | 'offline' | 'unknown';

export interface Category {
  id: string;
  name: string;
  /** Lucide icon name, resolved by the UI. */
  icon: string;
  description: string;
}

export interface VerificationChecks {
  /** HTTP(S) reachability + redirect chain inspection completed. */
  http: boolean;
  /** A real browser loaded the site in a clean, cookie-less context. */
  browser: boolean;
  /** No hard login/registration wall detected on the advertised tool. */
  noLoginWall: boolean;
  /** No mandatory API key detected for the core feature. */
  noApiKey: boolean;
  /** Core UI (editor/canvas/form/tool) is reachable without an account. */
  coreUiReachable: boolean;
  /** Site was re-checked after a temporary failure before a final decision. */
  retried?: boolean;
}

export interface VerificationRecord {
  status: VerificationStatus;
  method: 'http+browser' | 'http' | 'editorial';
  checks: VerificationChecks;
  /** Human-readable evidence, generated by the verifier. */
  evidence: string;
  httpStatus: number;
  finalUrl: string;
  checkedAt: string;
  durationMs?: number;
  attempts?: number;
}

export interface Site {
  id: string;
  name: string;
  url: string;
  domain: string;
  description: string;
  category: string;
  tags: string[];
  features?: string[];
  /** Core functionality can be used free of charge. */
  free: boolean;
  /** Must be false for a site to be published in the directory. */
  accountRequired: boolean;
  /** Must be false for a site to be published in the directory. */
  apiKeyRequired: boolean;
  /** True only when the project's own source licence has been confirmed. */
  openSource: boolean;
  sourceRepo?: string | null;
  license?: string | null;
  discoverySource: string;
  dateDiscovered: string;
  addedAt: string;
  lastVerifiedAt: string;
  verification: VerificationRecord;
  availability: Availability;
  /** Local logo path (populated by scripts/fetch-icons.ts) or null for the monogram fallback. */
  icon?: string | null;
  featured?: boolean;
  /** Consecutive failed availability checks; reset on a successful recheck. */
  consecutiveFailures?: number;
}

export interface Candidate {
  id: string;
  name: string;
  url: string;
  domain: string;
  description: string;
  category: string;
  tags: string[];
  suggestedBy: string;
  discoverySource: string;
  dateDiscovered: string;
  status: VerificationStatus;
  attempts: number;
  lastAttemptAt: string | null;
  verification: VerificationRecord | null;
  rejectionReason?: string | null;
  /** Set when a previously verified site regresses and needs investigation. */
  regressedFrom?: string | null;
  openSource?: boolean;
  sourceRepo?: string | null;
  license?: string | null;
  free?: boolean;
}

export type SourceType =
  | 'github-awesome'
  | 'github-search'
  | 'rss'
  | 'atom'
  | 'html-links'
  | 'no-signup-list';

export interface DiscoverySource {
  id: string;
  name: string;
  type: SourceType;
  url: string;
  enabled: boolean;
  /** Default category applied to discoveries from this source. */
  category?: string;
  tags?: string[];
  notes?: string;
  /** Maximum items taken from this source per run. */
  maxItems?: number;
  /** CSS selector used by html-links sources. */
  selector?: string;
  /** Extra feed/API query parameters. */
  query?: Record<string, string>;
}

export interface SourceHealthEntry {
  id: string;
  name: string;
  type: SourceType;
  status: 'ok' | 'failed' | 'skipped';
  items: number;
  durationMs: number;
  error?: string;
}

export interface RobotRunInfo {
  state: 'ok' | 'degraded' | 'failed' | 'idle';
  summary: string;
  lastRunAt: string | null;
  metrics: Record<string, number>;
}

export interface ScanMetadata {
  version: number;
  status: 'success' | 'partial' | 'failed' | 'running';
  schedule: string;
  scheduleIntervalMinutes: number;
  scheduleNote: string;
  lastScanAttemptAt: string | null;
  lastSuccessfulScanAt: string | null;
  lastCompletedScanAt: string | null;
  lastVerificationRunAt: string | null;
  lastAdditionAt: string | null;
  durationMs: number | null;
  counts: {
    sourcesChecked: number;
    sourcesFailed: number;
    discovered: number;
    pending: number;
    verified: number;
    rejected: number;
    rechecked: number;
    removed: number;
    duplicatesRemoved: number;
    totalSites: number;
    addedThisRun: number;
  };
  robots: {
    scout: RobotRunInfo;
    verifier: RobotRunInfo;
    curator: RobotRunInfo;
  };
  sourceHealth: SourceHealthEntry[];
  workflow: {
    provider: string;
    runId: string | null;
    runUrl: string | null;
    repositoryUrl: string;
    historyUrl: string;
    event: string;
    commit: string | null;
  };
  /** Set by the scan script when the run finished with recoverable errors. */
  notes?: string[];
}

export interface DirectoryData {
  sites: Site[];
  candidates: Candidate[];
  categories: Category[];
  sources: DiscoverySource[];
  metadata: ScanMetadata;
}
